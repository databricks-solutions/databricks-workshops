SELECT
      concat_ws('-',UniqueCarrier, FlightNum, event_date) as FlightKey,
      UniqueCarrier, 
      FlightNum, 
      TailNum, 
      event_date, 
      Year, 
      Month, 
      DayofMonth, 
      DayOfWeek,
      cast(CRSDepTime as string) CRSDepTime,
      cast(DepTime as string) DepTime,
      cast(CRSArrTime as string) CRSArrTime,
      cast(ArrTime as string) ArrTime,
      CRSElapsedTime,
      ActualElapsedTime,
      AirTime, 
      cast(ArrDelay as int) ArrDelay,
      cast(DepDelay as int) DepDelay,
      Origin,
      Dest, 
      Distance, 
      TaxiIn, 
      TaxiOut, 
      Cancelled, 
      CancellationCode,
      Diverted, 
      CarrierDelay, 
      WeatherDelay, 
      NASDelay, 
      SecurityDelay,
      LateAircraftDelay, 
      IsArrDelayed, 
      IsDepDelayed,
      current_timestamp() as CreatedTimestamp
FROM {{ var('source_catalog') }}.{{ var('source_schema') }}.airlines