CREATE STREAMING TABLE flights_bronze  (
  FlightKey STRING NOT NULL,
  UniqueCarrier STRING,
  FlightNum INT,
  TailNum STRING,
  event_date DATE,
  Year INT,
  Month INT,
  DayofMonth INT,
  DayOfWeek INT,
  CRSDepTime STRING,
  DepTime STRING,
  CRSArrTime STRING,
  ArrTime STRING,
  CRSElapsedTime INT,
  ActualElapsedTime STRING,
  AirTime STRING,
  ArrDelay INT,
  DepDelay INT,
  Origin STRING,
  Dest STRING,
  Distance STRING,
  TaxiIn STRING,
  TaxiOut STRING,
  Cancelled INT,
  CancellationCode STRING,
  Diverted INT,
  CarrierDelay INT,
  WeatherDelay INT,
  NASDelay INT,
  SecurityDelay INT,
  LateAircraftDelay INT,
  IsArrDelayed STRING,
  IsDepDelayed STRING,
  created_timestamp TIMESTAMP NOT NULL)
CLUSTER BY (FlightKey)
AS SELECT
      concat_ws('-',UniqueCarrier, FlightNum, event_date) as FlightKey, 
      UniqueCarrier, 
      FlightNum, 
      TailNum, 
      event_date, 
      Year, 
      Month, 
      DayofMonth, 
      DayOfWeek,
      cast(CRSDepTime as string) CRSDepTime,
      cast(DepTime as string) DepTime,
      cast(CRSArrTime as string) CRSArrTime,
      cast(ArrTime as string) ArrTime,
      CRSElapsedTime,
      ActualElapsedTime,
      AirTime, 
      cast(ArrDelay as int) ArrDelay,
      cast(DepDelay as int) DepDelay,
      Origin,
      Dest, 
      Distance, 
      TaxiIn, 
      TaxiOut, 
      Cancelled, 
      CancellationCode,
      Diverted, 
      CarrierDelay, 
      WeatherDelay, 
      NASDelay, 
      SecurityDelay,
      LateAircraftDelay, 
      IsArrDelayed, 
      IsDepDelayed,
      current_timestamp() as created_timestamp
FROM STREAM ${source_catalog}.${source_schema}.airlines;
